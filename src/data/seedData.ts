export function getCityCoordinates(cityName: string): { lat: number; lng: number } {
  const match = SUPPORTED_CITIES.find(
    (c) => c.city.toLowerCase() === cityName.trim().toLowerCase()
  );
  if (match) return { lat: match.lat, lng: match.lng };

  // Deterministic pseudo-coordinates for any custom city entered by a user
  let hash = 0;
  for (let i = 0; i < cityName.length; i++) {
    hash = (hash * 31 + cityName.charCodeAt(i)) % 10000;
  }
  return {
    lat: 12 + (hash % 1800) / 100,
    lng: 72 + ((hash * 7) % 1600) / 100,
  };
}

